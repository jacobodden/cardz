/**
 * Writes docs/design-history/index.html from the dated capture folders.
 *
 * The capture spec calls this after a run. To rebuild the page without
 * capturing (e.g. after editing this template):
 *
 *   npm run design:index
 */
import fs from 'node:fs'
import path from 'node:path'

export const GALLERY_ROOT = path.join('docs', 'design-history')

const DATED_DIR = /^\d{4}-\d{2}-\d{2}(-[\w-]+)?$/

function escapeHtml(text: string): string {
  return text.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;')
}

export function writeGalleryIndex(root: string = GALLERY_ROOT): void {
  const dates = fs
    .readdirSync(root, { withFileTypes: true })
    .filter((entry) => entry.isDirectory() && DATED_DIR.test(entry.name))
    .map((entry) => entry.name)
    .sort()
    .reverse()

  const imagesIn = (date: string) =>
    fs
      .readdirSync(path.join(root, date))
      .filter((file) => file.endsWith('.jpg'))
      .sort()

  const sections = dates
    .map((date) => {
      const figures = imagesIn(date)
        .map((file) => {
          const label = escapeHtml(file.replace(/\.jpg$/, '').replace(/-/g, ' '))
          const src = `${date}/${file}`
          return `      <figure>
        <a href="${src}"><img src="${src}" alt="${label}" loading="lazy"></a>
        <figcaption>${label}</figcaption>
      </figure>`
        })
        .join('\n')
      return `    <section>
      <h2>${escapeHtml(date)}</h2>
      <div class="gallery">
${figures}
      </div>
    </section>`
    })
    .join('\n')

  const latestCount = dates.length ? imagesIn(dates[0]).length : 0

  const html = `<!doctype html>
<html lang="en">
<head>
  <meta charset="utf-8">
  <meta name="viewport" content="width=device-width, initial-scale=1">
  <title>Design history — Cardz docs</title>
  <link rel="stylesheet" href="../assets/docs.css">
  <style>
    .gallery {
      display: grid;
      grid-template-columns: repeat(auto-fill, minmax(min(100%, 14rem), 1fr));
      gap: .75rem;
      margin: 1rem 0 0;
    }
    .gallery figure {
      margin: 0;
      background: var(--surface);
      border: 1px solid var(--line);
      border-radius: 10px;
      overflow: hidden;
    }
    .gallery a { display: block; }
    .gallery img { display: block; width: 100%; height: auto; }
    .gallery figcaption {
      padding: .45rem .65rem;
      border-top: 1px solid var(--line);
      color: var(--muted);
      font-size: .8rem;
    }
    details { margin: 0 0 1rem; }
    summary { cursor: pointer; font-weight: 600; }
  </style>
</head>
<body>
  <!-- Generated by tests/design-history/gallery.ts. Edit the template there, then run npm run design:index. -->
  <header class="band">
    <div class="wrap wide">
      <p class="crumbs"><a href="../index.html">Cardz docs</a></p>
      <h1>Design history</h1>
      <p class="lede">Dated screenshots of the Cardz UI, newest first. ${latestCount} images in the latest capture.</p>
    </div>
  </header>
  <main class="wrap wide">
    <details class="card">
      <summary>About these captures</summary>
      <p>This gallery is a human-readable record of how the design changes over time. The Playwright snapshots in <code>tests/visual/</code> are the machine-enforced regression guard.</p>
      <h3>Capturing a new milestone</h3>
      <pre><code>npm run design:capture</code></pre>
      <p>This writes JPEGs to <code>docs/design-history/&lt;YYYY-MM-DD&gt;/</code> and regenerates this page. Run it when a visual milestone lands, review the gallery, and commit the new dated folder with the updated page. A folder may carry a suffix (for example <code>2026-11-01-before-redesign</code>) to keep two milestones from the same day apart; every <code>YYYY-MM-DD*</code> folder is listed. The capture is not part of the normal test run or CI.</p>
      <h3>Visual regression baselines</h3>
      <pre><code>npm run test:visual          # compare against the committed baselines
npm run test:visual:update   # accept an intentional change</code></pre>
      <p>Baselines live in <code>tests/visual/current-ui.spec.ts-snapshots/</code>. Screenshots depend on font rendering, so both commands run inside the pinned Playwright container (podman or docker), the same image CI uses. Review the new images before committing them.</p>
    </details>
${sections}
  </main>
</body>
</html>
`

  fs.writeFileSync(path.join(root, 'index.html'), html)
}

if (import.meta.main) writeGalleryIndex()
